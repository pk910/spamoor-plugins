#!/usr/bin/env bash
# Compiles the contracts in this directory and regenerates bytecode.go.
#
#   ForsVerifier.sol          solc 0.8.30, via-ir, optimizer 200 runs, evm cancun
#   TestToken.sol             solc 0.8.30, optimizer 200 runs
#   ForsFrameAccount*.eas     geas (github.com/fjl/geas)
#
# Needs docker (ethereum/solc image) or a `solc` binary of the right version in PATH, jq,
# and geas (or Go, which runs it via `go run`).
set -euo pipefail

cd "$(dirname "$0")"

SOLC_VERSION=0.8.30
GEAS_VERSION=v0.3.3

solc_json() {
    # solc_json <file.sol> <extra args...> -> combined json on stdout
    local file=$1
    shift

    if command -v solc >/dev/null && solc --version | grep -q "Version: ${SOLC_VERSION}"; then
        solc "$file" --combined-json abi,bin "$@"
    else
        docker run --rm -v "$PWD:/contracts" "ethereum/solc:${SOLC_VERSION}" \
            "/contracts/$file" --combined-json abi,bin "$@"
    fi
}

extract() {
    # extract <combined json> <file.sol> <Contract> <field>
    jq -r --arg a "/contracts/$2:$3" --arg b "$2:$3" --arg f "$4" \
        '.contracts | (.[$a] // .[$b]) | .[$f]' <<<"$1"
}

geas_bin() {
    if command -v geas >/dev/null; then
        geas -a "$1"
    else
        go run "github.com/fjl/geas/cmd/geas@${GEAS_VERSION}" -a "$1"
    fi
}

echo "compiling ForsVerifier.sol"
verifier_json=$(solc_json ForsVerifier.sol --via-ir --optimize --optimize-runs 200 --evm-version cancun)
verifier_bin=$(extract "$verifier_json" ForsVerifier.sol ForsVerifier bin)

echo "compiling TestToken.sol"
token_json=$(solc_json TestToken.sol --optimize --optimize-runs 200)
token_bin=$(extract "$token_json" TestToken.sol TestToken bin)
token_abi=$(extract "$token_json" TestToken.sol TestToken abi)

echo "assembling ForsFrameAccount"
account_initcode=$(geas_bin ForsFrameAccount.ctor.eas)
account_runtime=$(geas_bin ForsFrameAccount.eas)

# the ABI is embedded as a Go string literal
token_abi_go=$(jq -c . <<<"$token_abi" | sed 's/\\/\\\\/g; s/"/\\"/g')

cat >bytecode.go <<GO
// Code generated by build.sh. DO NOT EDIT.

package contract

// ForsFrameAccountInitcodeHex is ForsFrameAccount.ctor.eas assembled with geas ${GEAS_VERSION}.
// Append abi.encode(address verifier, address initialOwner) to deploy.
const ForsFrameAccountInitcodeHex = "0x${account_initcode}"

// ForsFrameAccountRuntimeHex is the runtime the constructor installs (ForsFrameAccount.eas).
const ForsFrameAccountRuntimeHex = "0x${account_runtime}"

// ForsVerifierInitcodeHex is ForsVerifier.sol compiled with solc ${SOLC_VERSION}, via-ir,
// optimizer 200 runs, evm cancun. Stateless; recover(bytes,bytes32) returns the signer.
const ForsVerifierInitcodeHex = "0x${verifier_bin}"

// TestTokenABI is the ABI of TestToken.sol. transferMint(to, amount) mints to the caller
// and transfers, so no prior balance is needed.
const TestTokenABI = "${token_abi_go}"

// TestTokenBin is TestToken.sol compiled with solc ${SOLC_VERSION}, optimizer 200 runs.
const TestTokenBin = "0x${token_bin}"
GO

gofmt -w bytecode.go
echo "bytecode.go regenerated"
